// جدول {محافظة: سعر نهائي} — بيتبني أوتوماتيك من المناطق فوق
export const GOVERNORATE_RATES = Object.fromEntries(
  Object.entries(GOVERNORATE_TO_ZONE).map(([gov, zone]) => [gov, zoneFee(zone)])
);
export const GOVERNORATE_NAMES = Object.keys(GOVERNORATE_TO_ZONE);
export const OTHER_GOVERNORATE = "محافظة تانية";

export function getGovernorateFee(name) {
  if (!name || name === OTHER_GOVERNORATE) return null;
  return GOVERNORATE_RATES.hasOwnProperty(name) ? GOVERNORATE_RATES[name] : null;
}

