const VAT = 0.14; // ضريبة القيمة المضافة

// أسعار مايلرز قبل الضريبة (أول 2 كيلو + سعر الكيلو الزيادة)
// ملحوظة: إحنا بنحسب للعميل سعر "أول 2 كيلو" بس، لأن أوردرات الموقع
// (خبز/خميرة/أدوات) عمرها ما بتعدي 2 كيلو تقريباً. لو ضفت منتجات تقيلة
// بعدين، هنحتاج نضيف وزن لكل منتج ونستخدم extraKg.
export const MYLERZ_ZONES = {
  delta:      { label: "الدلتا",            first2kg: 75,  extraKg: 7 },
  alex:       { label: "الإسكندرية",        first2kg: 80,  extraKg: 8 },
  cairoGiza:  { label: "القاهرة والجيزة",   first2kg: 85,  extraKg: 10 },
  canal:      { label: "مدن القناة",        first2kg: 85,  extraKg: 12 },
  upperEgypt: { label: "الصعيد",            first2kg: 95,  extraKg: 12 },
  sinai:      { label: "سيناء",             first2kg: 140, extraKg: 13 },
};

// السعر النهائي اللي العميل بيدفعه = السعر × 1.14 (بالكسور زي ما هو)
function zoneFee(zoneKey) {
  const z = MYLERZ_ZONES[zoneKey];
  if (!z) return null;
  return Math.round(z.first2kg * (1 + VAT) * 100) / 100; // مثال: 75 → 85.5
}

