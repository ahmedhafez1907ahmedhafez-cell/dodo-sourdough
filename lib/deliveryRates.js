// رسم تغليف ثابت — بيتضاف مرة واحدة لكل أوردر (مش لكل منتج)
export const PACKAGING_FEE = 5;

export function getGovernorateTier(name) {
  if (!name || name === OTHER_GOVERNORATE) return null;
  const key = GOVERNORATE_TO_TIER[name];
  return key ? SHIPPING_TIERS[key] : null;
}

/** سعر "الكيلو الأول" بس للمحافظة — للعرض السريع قبل ما نعرف وزن الأوردر */
export function getGovernorateFee(name) {
  const tier = getGovernorateTier(name);
  return tier ? tier.firstKilo : null;
}

/**
 * عدد الكيلوهات "الزيادة" اللي هتتحسب بسعر إضافي — بترجع من وزن
 * الخميرة السائلة بس (المنتج الوحيد اللي بيتباع بالجرام). أي جزء من
 * الكيلو بيتحسب كيلو كامل (Math.ceil).
 */
export function extraKgFromGrams(grams) {
  const g = Number(grams) || 0;
  if (g <= 0) return 0;
  return Math.ceil(g / 1000);
}

/** السعر الكامل للتوصيل: الكيلو الأول + (الكيلوهات الزيادة × سعرها) */
export function getGovernorateShippingFee(name, extraKg = 0) {
  const tier = getGovernorateTier(name);
  if (!tier) return null;
  const kg = Math.max(0, Math.round(Number(extraKg) || 0));
  return tier.firstKilo + kg * tier.extraKg;
}

