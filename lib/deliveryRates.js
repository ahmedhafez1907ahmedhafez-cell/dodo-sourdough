// السعر النهائي اللي العميل بيدفعه = السعر × 1.14 (بالكسور زي ما هو)
function zoneFee(zoneKey) {
  const z = SHIPPING_ZONES[zoneKey];
  if (!z) return null;
  return Math.round(z.price * (1 + VAT) * 100) / 100; // مثال: 97 → 110.58
}

