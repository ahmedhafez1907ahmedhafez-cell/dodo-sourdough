/** نسبة العربون من إجمالي الأوردر */
export const DEPOSIT_RATIO = 0.5;

/** الرقم اللي العميل بيحوّل عليه (فودافون كاش / إنستاباي) */
export const DEPOSIT_WALLET = "01006461698";

/** بنقرّب لأقرب جنيه لفوق — أسهل على العميل من كسور المحفظة */
export function depositFor(total) {
  const t = Number(total) || 0;
  return Math.ceil(t * DEPOSIT_RATIO);
}

/** الباقي بعد العربون */
export function remainderFor(total) {
  const t = Number(total) || 0;
  return Math.round((t - depositFor(t)) * 100) / 100;
}
