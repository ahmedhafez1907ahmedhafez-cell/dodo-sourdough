/** فيه نوتس مكتوبة فعلاً؟ */
export function hasNotes(product) {
  return !!(product && typeof product.notes === "string" && product.notes.trim());
}

/**
 * بيقسّم النص لفقرات. أول سطر في الفقرة لو قصير ومفيهوش نقطة
 * بيتعامل كعنوان — عشان الشكل يطلع منظم من غير ما الأدمن
 * يتعلم أي صيغة خاصة.
 */
export function parseNotes(text) {
  return String(text || "")
    .split(/\n\s*\n/)
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => {
      const lines = block.split("\n").map((l) => l.trim()).filter(Boolean);
      const first = lines[0] || "";
      const isHeading = lines.length > 1 && first.length <= 40 && !/[.،:]$/.test(first);
      return isHeading
        ? { title: first, lines: lines.slice(1) }
        : { title: null, lines };
    });
}
